const dicts = { en, de };
export type Lang = keyof typeof dicts;

function systemLang(): Lang {
  const langs = typeof navigator === "undefined" ? [] : [navigator.language, ...(navigator.languages ?? [])];
  return langs.some((l) => l?.toLowerCase().startsWith("de")) ? "de" : "en";
}

const state = $state<{ lang: Lang }>({ lang: systemLang() });

/** "auto", "en" or "de" from the config */
export function setLanguage(pref: string) {
  state.lang = pref === "en" || pref === "de" ? pref : systemLang();
  document.documentElement.lang = state.lang;
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text = dicts[state.lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`));
}
