//! Running context-menu actions and status commands.
//!
//! Background actions run without a terminal. So that `sudo` inside a script
//! can still ask for the password, SUDO_ASKPASS points to a small helper that
//! shows a graphical prompt (rofi, zenity, kdialog or ssh-askpass, whatever is
//! installed). sudo uses it automatically when there is no terminal; `setsid`
//! guarantees that, even when SvcDeck itself was started from a terminal.

use crate::config::{self, Action, ActionMode, App, Config};
use crate::locale::tr;
use crate::terminal;
use serde::Serialize;
use std::fs;
use std::io::Write;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

const ASKPASS: &str = r#"#!/usr/bin/env bash
# Generated by SvcDeck. Graphical password prompt for sudo (SUDO_ASKPASS).
prompt="${1:-Password}"
title="SvcDeck"
desktop="${XDG_CURRENT_DESKTOP,,}"
have() { command -v "$1" >/dev/null 2>&1; }

# Native dialog of the desktop first, then whatever is installed
if [[ "$desktop" == *kde* ]] && have kdialog; then
  exec kdialog --title "$title" --password "$prompt"
fi
if [[ "$desktop" == *gnome* || "$desktop" == *xfce* || "$desktop" == *cinnamon* || "$desktop" == *mate* ]] && have zenity; then
  exec zenity --password --title="$title: $prompt"
fi
if have rofi; then
  exec rofi -dmenu -password -p "sudo" -mesg "$title: $prompt" \
    -theme-str 'listview { enabled: false; } window { width: 32em; }' </dev/null
fi
have zenity && exec zenity --password --title="$title: $prompt"
have kdialog && exec kdialog --title "$title" --password "$prompt"
for p in /usr/lib/ssh/ssh-askpass /usr/lib/openssh/ssh-askpass /usr/bin/ssh-askpass /usr/bin/ksshaskpass; do
  [[ -x "$p" ]] && exec "$p" "$prompt"
done
echo "SvcDeck: no password dialog found (install zenity, kdialog, rofi or x11-ssh-askpass)" >&2
exit 1
"#;

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ActionResult {
    pub ok: bool,
    pub code: Option<i32>,
    /// stdout and stderr combined (ANSI colors are kept)
    pub output: String,
    pub detached: bool,
}

/// Writes the askpass helper (0700) and returns its path.
pub fn ensure_askpass() -> Result<PathBuf, String> {
    let dir = config::config_dir();
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let path = dir.join("askpass.sh");
    let current = fs::read_to_string(&path).unwrap_or_default();
    if current != ASKPASS {
        let mut f = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o700)
            .open(&path)
            .map_err(|e| e.to_string())?;
        f.write_all(ASKPASS.as_bytes()).map_err(|e| e.to_string())?;
    }
    Ok(path)
}

fn find<'a>(
    cfg: &'a Config,
    app_id: &str,
    action_id: &str,
) -> Result<(&'a App, &'a Action), String> {
    let app = cfg
        .apps
        .iter()
        .find(|a| a.id == app_id)
        .ok_or_else(|| format!("{}: {app_id}", tr("Unknown app", "Unbekannte App")))?;
    let action = app
        .actions
        .iter()
        .find(|a| a.id == action_id)
        .ok_or_else(|| {
            format!(
                "{}: {} {action_id}",
                app.name,
                tr("unknown action", "unbekannte Aktion")
            )
        })?;
    Ok((app, action))
}

pub fn work_dir(app: &App) -> Result<PathBuf, String> {
    if app.dir.trim().is_empty() {
        return Ok(config::home_dir());
    }
    let p = PathBuf::from(app.dir.trim());
    if !p.is_dir() {
        return Err(format!(
            "{}: {} {}",
            app.name,
            tr("directory not found:", "Verzeichnis fehlt:"),
            p.display()
        ));
    }
    Ok(p)
}

fn base_command(program: &str, dir: &Path, askpass: &Path) -> Command {
    let mut cmd = Command::new(program);
    cmd.current_dir(dir)
        .env("SUDO_ASKPASS", askpass)
        // Keep colors; the UI turns ANSI codes into colors
        .env("TERM", "xterm-256color")
        .stdin(Stdio::null());
    cmd
}

pub fn run(app_id: &str, action_id: &str) -> Result<ActionResult, String> {
    let cfg = config::load()?;
    let (app, action) = find(&cfg, app_id, action_id)?;
    let dir = work_dir(app)?;
    let askpass = ensure_askpass()?;

    match action.mode {
        ActionMode::Capture => {
            // setsid -w: new session without a controlling terminal, waits
            let out = base_command("setsid", &dir, &askpass)
                .args(["-w", "bash", "-lc", &action.command])
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .output()
                .map_err(|e| format!("{}: {e}", tr("Could not start", "Start fehlgeschlagen")))?;
            let mut output = String::from_utf8_lossy(&out.stdout).into_owned();
            let err = String::from_utf8_lossy(&out.stderr);
            if !err.trim().is_empty() {
                if !output.is_empty() && !output.ends_with('\n') {
                    output.push('\n');
                }
                output.push_str(&err);
            }
            Ok(ActionResult {
                ok: out.status.success(),
                code: out.status.code(),
                output,
                detached: false,
            })
        }
        ActionMode::Terminal => {
            let invocation = terminal::resolve(&cfg.terminal).ok_or_else(|| {
                tr(
                    "No terminal found. Set one in the settings or install e.g. kitty, foot or alacritty.",
                    "Kein Terminal gefunden. In den Einstellungen eintragen oder z. B. kitty, foot oder alacritty installieren.",
                )
                .to_string()
            })?;
            let (program, rest) = invocation.split_first().expect("non-empty invocation");
            // Keep the window open until a key is pressed
            let wrapped = format!(
                "{}\nprintf '\\n[%s %s] ' {} {}\nread -rsn1",
                action.command,
                shell_quote(&action.label),
                shell_quote(tr(
                    "finished, press any key to close",
                    "beendet, Taste zum Schließen"
                ))
            );
            let mut child = base_command(program, &dir, &askpass)
                .args(rest)
                .args(["bash", "-lc", &wrapped])
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .spawn()
                .map_err(|e| {
                    format!(
                        "{} '{program}': {e}",
                        tr("Could not start terminal", "Terminal startet nicht")
                    )
                })?;
            // Reap the child so no zombie process is left behind
            std::thread::spawn(move || {
                let _ = child.wait();
            });
            Ok(ActionResult {
                ok: true,
                code: None,
                output: String::new(),
                detached: true,
            })
        }
    }
}

/// Runs a status command; true when it exits with 0 within the timeout.
/// No askpass here: a status check must never prompt for a password.
pub fn check_command(app: &App, command: &str, timeout: Duration) -> bool {
    let Ok(dir) = work_dir(app) else { return false };
    // Without -w, setsid does not fork here (our child is no group leader):
    // bash keeps the PID, which is then also the session/process group ID.
    // That lets a timeout kill the whole group, not only the shell.
    let Ok(mut child) = Command::new("setsid")
        .args(["bash", "-lc", command])
        .current_dir(dir)
        .env("SUDO_ASKPASS", "/bin/false")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
    else {
        return false;
    };
    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return status.success(),
            Ok(None) if start.elapsed() < timeout => std::thread::sleep(Duration::from_millis(40)),
            _ => {
                let _ = Command::new("kill")
                    .args(["-KILL", "--", &format!("-{}", child.id())])
                    .stdout(Stdio::null())
                    .stderr(Stdio::null())
                    .status();
                let _ = child.kill();
                let _ = child.wait();
                return false;
            }
        }
    }
}

fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app_in(dir: &str) -> App {
        App {
            id: "t".into(),
            name: "T".into(),
            url: String::new(),
            icon: String::new(),
            glyph: String::new(),
            dir: dir.into(),
            health: String::new(),
            health_command: String::new(),
            actions: Vec::new(),
        }
    }

    #[test]
    fn shell_quote_escapes_single_quotes() {
        assert_eq!(shell_quote("plain"), "'plain'");
        assert_eq!(shell_quote("it's"), r"'it'\''s'");
    }

    #[test]
    fn status_command_uses_exit_code() {
        let app = app_in("/");
        assert!(check_command(&app, "true", Duration::from_secs(5)));
        assert!(!check_command(&app, "false", Duration::from_secs(5)));
        assert!(!check_command(&app, "exit 3", Duration::from_secs(5)));
    }

    #[test]
    fn status_command_times_out() {
        let app = app_in("/");
        let start = Instant::now();
        assert!(!check_command(&app, "sleep 30", Duration::from_millis(300)));
        assert!(
            start.elapsed() < Duration::from_secs(5),
            "timeout did not kill the command"
        );
    }

    #[test]
    fn status_command_runs_in_app_dir() {
        let app = app_in("/tmp");
        assert!(check_command(
            &app,
            "[ \"$PWD\" = /tmp ]",
            Duration::from_secs(5)
        ));
    }

    #[test]
    fn missing_dir_is_an_error() {
        assert!(work_dir(&app_in("/definitely/not/here")).is_err());
        assert!(!check_command(
            &app_in("/definitely/not/here"),
            "true",
            Duration::from_secs(5)
        ));
    }

    #[test]
    fn askpass_script_is_valid_bash() {
        let status = Command::new("bash")
            .args(["-n", "-c", ASKPASS])
            .status()
            .expect("bash available");
        assert!(status.success());
    }
}
